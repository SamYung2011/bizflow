const dictionaries = { zh, en, fr };

export function translateOcppCommand(lang, key, values = {}) {
  const template =
    dictionaries[lang]?.[key] ?? dictionaries.zh[key] ?? String(key);
  return Object.entries(values).reduce(
    (text, [name, value]) =>
      text.replaceAll(`{${name}}`, String(value)),
    template,
  );
}
