export const ocppCopy = { zh, en, fr };
export function translateOcpp(lang, key, values = {}) {
  const template = ocppCopy[lang]?.[key] ?? ocppCopy.zh[key] ?? key;
  return Object.entries(values).reduce(
    (text, [name, value]) => text.replaceAll(`{${name}}`, String(value)),
    template,
  );
}
