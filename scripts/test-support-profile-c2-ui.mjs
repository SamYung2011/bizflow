import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE ? pathToFileURL(process.env.PLAYWRIGHT_MODULE).href : 'playwright');
const origin = process.env.PREVIEW_ORIGIN || 'http://127.0.0.1:5199';
const output = process.env.EVIDENCE_DIR || '/tmp/support-profile-c2-1019';
await mkdir(output, {recursive:true});
const browser = await chromium.launch({headless:true,channel:'chrome'});
const page = await browser.newPage({viewport:{width:1440,height:1100}});
const errors=[],external=[];
page.on('pageerror', error=>errors.push(error.message));
await page.route('**/*', route=>{
  if(new URL(route.request().url()).origin===origin) return route.continue();
  external.push(route.request().url());return route.abort();
});
try {
  await page.goto(`${origin}/scripts/tg5-c-preview.html?history=1`);
  await page.locator('.support-conversation').filter({hasText:'Alex Chan'}).first().click();
  await page.locator('.customer-name-button').click();
  const drawer=page.getByRole('dialog',{name:'客戶檔案'}), rows=drawer.locator('.customer-history');
  await drawer.getByRole('button',{name:'展開',exact:true}).waitFor();
  assert.equal(await rows.count(),5);
  assert((await rows.allTextContents())[0].includes('HM-CS-000001'));
  await drawer.getByText('歷史對話',{exact:true}).scrollIntoViewIfNeeded();
  await page.screenshot({path:`${output}/c2-history-five.png`});
  await drawer.getByRole('button',{name:'展開',exact:true}).click();
  await page.waitForFunction(()=>document.querySelectorAll('.customer-history').length===20);
  assert((await rows.first().textContent()).includes('HM-CS-000001'));
  const first=await rows.allTextContents();
  const dimensions=await drawer.locator('.customer-history-list').evaluate(node=>({height:node.clientHeight,scroll:node.scrollHeight,overflow:getComputedStyle(node).overflowY}));
  assert(dimensions.height<=360 && dimensions.scroll>dimensions.height && dimensions.overflow==='auto');
  await page.screenshot({path:`${output}/c2-history-expanded.png`});
  console.log('PROFILE_C2_UI 1: five latest; expansion fetches first 20 and scrolls within 360px');
  await drawer.getByRole('button',{name:'下一頁',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('.customer-history-controls span')?.textContent==='2' && document.querySelectorAll('.customer-history').length===20);
  const second=await rows.allTextContents();
  assert(second.every(row=>!first.includes(row)));
  await drawer.getByRole('button',{name:'下一頁',exact:true}).click();
  await page.waitForFunction(()=>document.querySelectorAll('.customer-history').length===5);
  assert(await drawer.getByRole('button',{name:'下一頁',exact:true}).isDisabled());
  await drawer.getByRole('button',{name:'上一頁',exact:true}).click();
  await page.waitForFunction(()=>document.querySelectorAll('.customer-history').length===20);
  assert.deepEqual(await rows.allTextContents(),second);
  await drawer.getByRole('button',{name:'收起',exact:true}).click();
  assert.equal(await rows.count(),5);
  assert.equal(await drawer.getByRole('button',{name:'上一頁',exact:true}).count(),0);
  console.log('PROFILE_C2_UI 2: 45 conversations paginate 20/20/5 without overlap and collapse restores five');
  await rows.filter({hasText:'HM-CS-000006'}).click();
  await drawer.waitFor({state:'detached'});
  await page.getByText('The receipt has been corrected. Thank you, Alex.',{exact:true}).waitFor();
  console.log('PROFILE_C2_UI 3: historical conversation opens in the existing support workspace');
  assert.deepEqual(errors,[]);assert.deepEqual(external,[]);
  console.log('PROFILE_C2_UI_CHECK=3/3');
} finally {await browser.close();}
